      </details>
      <details class="faq-item">
        <summary><span class="n">03</span>How do I know which size to order?</summary>
        <p class="a">Check the fit guide above for the four core measurements, and if you're between sizes on a specific piece, message a stylist &mdash; we'll tell you honestly which way that item runs.</p>
      </details>
      <details class="faq-item">
        <summary><span class="n">04</span>Where are your pieces made?</summary>
        <p class="a">We work with a small set of workshops in the Northeast and abroad, all vetted for fair labor practices; each product page names the specific workshop that finished it.</p>
      </details>
